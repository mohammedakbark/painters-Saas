/** Initial market (D-020): preselected for a new address. */
export const DEFAULT_STATE_CODE = 'KL';

/** The code of a state given its code or name (as map services return). */
export function matchIndianState(
  value: string | null | undefined,
): string | null {
  if (!value) {
    return null;
  }
  const needle = value.trim().toLowerCase();
  const match = INDIAN_STATES.find(
    (state) =>
      state.code.toLowerCase() === needle ||
      state.name.toLowerCase() === needle,
  );
  return match?.code ?? null;
}
