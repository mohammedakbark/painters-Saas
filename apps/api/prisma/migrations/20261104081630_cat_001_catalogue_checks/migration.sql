-- Hand-written constraints for the brand catalogue (CAT-001). Not expressible in
-- schema.prisma; keep them in sync with src/catalogue/catalogue.schemas.ts.

-- Names are stored trimmed; name_key is lower(name) for case-insensitive uniqueness.
ALTER TABLE "catalogue_categories" ADD CONSTRAINT "catalogue_categories_name_check" CHECK (
  "name" = btrim("name") AND char_length("name") BETWEEN 2 AND 60 AND "name_key" = lower("name")
);
ALTER TABLE "brands" ADD CONSTRAINT "brands_name_check" CHECK (
  "name" = btrim("name") AND char_length("name") BETWEEN 2 AND 80 AND "name_key" = lower("name")
);
ALTER TABLE "catalogue_products" ADD CONSTRAINT "catalogue_products_text_check" CHECK (
  "name" = btrim("name") AND char_length("name") BETWEEN 2 AND 120 AND "name_key" = lower("name") AND
  ("description" IS NULL OR ("description" = btrim("description") AND char_length("description") BETWEEN 1 AND 1000))
);

-- Product images: key and time together; the key is generated by the API inside the product's prefix.
ALTER TABLE "catalogue_products" ADD CONSTRAINT "catalogue_products_image_check" CHECK (
  num_nonnulls("image_key", "image_updated_at") IN (0, 2) AND
  ("image_key" IS NULL OR "image_key" ~ ('^catalogue/products/' || "id"::text || '/image/[0-9a-f-]{36}$'))
);

-- Pack sizes are positive (up to 9,999,999.999).
ALTER TABLE "catalogue_packs" ADD CONSTRAINT "catalogue_packs_quantity_check" CHECK ("quantity" > 0);

-- Shade codes are upper case as printed on shade cards; preview colours are #RRGGBB.
ALTER TABLE "shades" ADD CONSTRAINT "shades_text_check" CHECK (
  "code" ~ '^[A-Z0-9][A-Z0-9 ./-]{0,19}$' AND "code" = btrim("code") AND
  "name" = btrim("name") AND char_length("name") BETWEEN 1 AND 80 AND
  ("preview_hex" IS NULL OR "preview_hex" ~ '^#[0-9A-F]{6}$')
);

-- Search (ILIKE) and browsing indexes. Trigram indexes can follow if search gets slow.
CREATE INDEX "shades_brand_id_name_idx" ON "shades" ("brand_id", "name");
CREATE INDEX "catalogue_products_brand_id_name_idx" ON "catalogue_products" ("brand_id", "name");

-- Defense in depth (ADR 0005): RLS with no policies; the API is the table owner.
ALTER TABLE "catalogue_categories" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "brands" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "catalogue_products" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "catalogue_packs" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "shades" ENABLE ROW LEVEL SECURITY;
