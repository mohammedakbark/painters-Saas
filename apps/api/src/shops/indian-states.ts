export type IndianStateCode = (typeof INDIAN_STATES)[number]['code'];

export const INDIAN_STATE_CODES = INDIAN_STATES.map((state) => state.code) as [
  IndianStateCode,
  ...IndianStateCode[],
];

const NAMES = new Map<string, string>(
  INDIAN_STATES.map((state) => [state.code, state.name]),
);

/** The display name of a stored state code (the code itself if unknown). */
export function indianStateName(code: string): string {
  return NAMES.get(code) ?? code;
}
